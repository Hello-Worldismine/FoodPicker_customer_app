const now = new Date();

function hoursFromNow(h) {
  const d = new Date(now);
  d.setHours(d.getHours() + h);
  return d.toISOString();
}

function todayAt(h, m = 0) {
  const d = new Date(now);
  d.setHours(h, m, 0, 0);
  return d.toISOString();
}

